CREATE TABLE IF NOT EXISTS comment_job (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    video_id VARCHAR(64) NOT NULL UNIQUE,
    profile_name VARCHAR(128) NOT NULL,
    body VARCHAR(120) NOT NULL,
    status VARCHAR(32) NOT NULL CHECK (status IN ('APPROVED','RUNNING','COMPLETED','FAILED','CONFIRMATION_PENDING')),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    version BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS comment_job_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id BIGINT NOT NULL REFERENCES comment_job(id),
    status VARCHAR(32) NOT NULL CHECK (status IN ('APPROVED','RUNNING','COMPLETED','FAILED','CONFIRMATION_PENDING')),
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
    failure_reason VARCHAR(1000),
    screenshot_path VARCHAR(512)
);

CREATE INDEX IF NOT EXISTS idx_comment_job_event_history ON comment_job_event(job_id, occurred_at, id);
